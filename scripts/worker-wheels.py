"""Lock, download and verify the vision worker's wheels for the UNO Q.

The worker runs MediaPipe on a uv-managed CPython 3.12 for Linux ARM64. The
release ZIP carries every wheel it needs next to the MediaPipe wheel, so a
first start, a uv upgrade or a cleared cache never needs PyPI.

  lock   Resolve python/worker-requirements.txt with uv (a maintainer step).
         Versions already in the lock are kept unless --upgrade is given.
  fetch  Download the locked wheels into output/worker-wheels, checking each
         SHA-256, before building the App Lab package.
  check  Confirm a folder holds exactly the locked wheels with their hashes.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "python/worker-requirements.txt"
MEDIAPIPE = ROOT / "python/worker-wheels/mediapipe-0.10.35+powerglove.cpu1-cp312-cp312-linux_aarch64.whl"
DESTINATION = ROOT / "output/worker-wheels"
# The UNO Q worker interpreter and the glibc of the App Lab base image.
PYTHON = (3, 12)
GLIBC = (2, 41)
WHEEL = re.compile(r"^(?P<name>[^-]+)-(?P<version>[^-]+)(?:-\d[^-]*)?"
                   r"-(?P<python>[^-]+)-(?P<abi>[^-]+)-(?P<platform>[^-]+)\.whl$")
ENTRY = re.compile(r"^(?P<name>[A-Za-z0-9._-]+)==(?P<version>\S+) --hash=sha256:(?P<sha>[0-9a-f]{64})$")
HEADER = """\
# Generated by scripts/worker-wheels.py lock; edit with that command, not by hand.
# The UNO Q vision worker's wheels besides the MediaPipe wheel in worker-wheels/:
# CPython 3.12 on Linux ARM64. Each entry names the one wheel the release ZIP
# carries for it and that wheel's SHA-256.
"""


def entries(lock: Path = LOCK) -> list[dict]:
    """Return the locked wheels as name, version, sha256 and filename."""
    result, wheel = [], None
    for line in lock.read_text().splitlines():
        if line.startswith("# wheel: "):
            wheel = line[len("# wheel: "):].strip()
        elif line and not line.startswith("#"):
            match = ENTRY.match(line)
            if not match or not wheel:
                raise ValueError(f"Unexpected worker lock line: {line}")
            result.append(dict(match.groupdict(), filename=wheel))
            wheel = None
    return result


def wheel_score(filename: str) -> tuple | None:
    """Rank a wheel for the UNO Q worker; None when it cannot install there."""
    match = WHEEL.match(filename)
    if not match:
        return None
    pythons = set(match["python"].split("."))
    abis = set(match["abi"].split("."))
    cpython = "cp%d%d" % PYTHON
    stable = "abi3" in abis and any(
        re.fullmatch(r"cp3(\d+)", tag) and int(tag[3:]) <= PYTHON[1] for tag in pythons)
    if not (pythons & {cpython, "py3", "py%d%d" % PYTHON} or stable):
        return None
    if not abis & {"none", "abi3", cpython}:
        return None
    best = None
    for platform in match["platform"].split("."):
        if platform == "any":
            score = (0, (0, 0))
        else:
            tagged = re.fullmatch(r"manylinux_(\d+)_(\d+)_aarch64", platform)
            legacy = {"manylinux2014_aarch64": (2, 17)}.get(platform)
            glibc = (int(tagged[1]), int(tagged[2])) if tagged else legacy
            if glibc is None or glibc > GLIBC:
                continue
            score = (1, glibc)
        best = score if best is None or score > best else best
    if best is None:
        return None
    return (cpython in abis, best, cpython in pythons)


def pypi_files(name: str, version: str) -> list[dict]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=60) as response:
        return json.load(response)["urls"]


def choose(name: str, version: str, hashes: set[str]) -> dict:
    """Pick the best UNO Q wheel among the files uv resolved for a pin."""
    files = [item for item in pypi_files(name, version)
             if item["packagetype"] == "bdist_wheel" and item["digests"]["sha256"] in hashes
             and wheel_score(item["filename"]) is not None]
    if not files:
        raise ValueError(f"No Linux ARM64 CPython 3.12 wheel for {name}=={version}")
    return max(files, key=lambda item: wheel_score(item["filename"]))


def lock(uv: str, upgrade: bool, constraints: Path | None = None) -> None:
    with tempfile.TemporaryDirectory() as directory:
        work = Path(directory)
        (work / "in.txt").write_text(f"{MEDIAPIPE}\n")
        command = [uv, "pip", "compile", "--quiet", str(work / "in.txt"), "--python-version", "%d.%d" % PYTHON,
                   "--python-platform", "aarch64-unknown-linux-gnu", "--generate-hashes",
                   "--no-header", "--no-annotate", "-o", str(work / "out.txt")]
        if LOCK.is_file() and not upgrade:
            (work / "keep.txt").write_text("".join(
                f"{item['name']}=={item['version']}\n" for item in entries()))
            command += ["-c", str(work / "keep.txt")]
        if constraints is not None:
            command += ["-c", str(constraints)]
        subprocess.run(command, check=True)
        resolved = (work / "out.txt").read_text().replace("\\\n", " ")
    lines = [HEADER]
    for line in resolved.splitlines():
        parts = line.split()
        if not parts or "==" not in parts[0]:
            continue  # the local MediaPipe wheel and blank lines
        name, version = parts[0].split("==", 1)
        hashes = {part.split(":", 1)[1] for part in parts[1:] if part.startswith("--hash=sha256:")}
        chosen = choose(name, version, hashes)
        lines.append(f"# wheel: {chosen['filename']}\n"
                     f"{name}=={version} --hash=sha256:{chosen['digests']['sha256']}\n")
    LOCK.write_text("".join(lines))
    print(f"Locked {len(lines) - 1} worker wheels in {LOCK.relative_to(ROOT)}")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def problems(folder: Path, lock_file: Path = LOCK) -> list[str]:
    """Describe how folder differs from the locked wheel set; empty when it matches."""
    expected = {item["filename"]: item["sha"] for item in entries(lock_file)}
    present = {path.name for path in folder.glob("*.whl")} if folder.is_dir() else set()
    found = [f"missing {name}" for name in sorted(set(expected) - present)]
    found += [f"unexpected {name}" for name in sorted(present - set(expected))]
    found += [f"checksum mismatch {name}" for name in sorted(set(expected) & present)
              if sha256(folder / name) != expected[name]]
    return found


def fetch(destination: Path) -> None:
    destination.mkdir(parents=True, exist_ok=True)
    wanted = entries()
    for item in wanted:
        target = destination / item["filename"]
        if target.is_file() and sha256(target) == item["sha"]:
            continue
        url = next((file["url"] for file in pypi_files(item["name"], item["version"])
                    if file["filename"] == item["filename"]
                    and file["digests"]["sha256"] == item["sha"]), None)
        if url is None:
            raise ValueError(f"PyPI no longer lists {item['filename']}")
        partial = target.with_suffix(".part")
        with urllib.request.urlopen(url, timeout=120) as response, partial.open("wb") as output:
            for block in iter(lambda: response.read(1 << 20), b""):
                output.write(block)
        if sha256(partial) != item["sha"]:
            partial.unlink()
            raise ValueError(f"Checksum mismatch downloading {item['filename']}")
        partial.replace(target)
    names = {item["filename"] for item in wanted}
    for stale in destination.glob("*.whl"):
        if stale.name not in names:
            stale.unlink()
    size = sum((destination / name).stat().st_size for name in names)
    print(f"{len(names)} worker wheels verified in {destination} ({size / 1048576:.0f} MB)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    locking = commands.add_parser("lock", help="resolve the lock with uv")
    locking.add_argument("--uv", default="uv", help="uv executable (default: uv on PATH)")
    locking.add_argument("--upgrade", action="store_true", help="allow newer versions")
    locking.add_argument("--constraints", type=Path, help="extra pins, e.g. versions a board runs")
    fetching = commands.add_parser("fetch", help="download and verify the locked wheels")
    fetching.add_argument("--destination", type=Path, default=DESTINATION)
    checking = commands.add_parser("check", help="verify a folder of wheels against the lock")
    checking.add_argument("folder", type=Path, nargs="?", default=DESTINATION)
    args = parser.parse_args()
    if args.command == "lock":
        lock(args.uv, args.upgrade, args.constraints)
    elif args.command == "fetch":
        fetch(args.destination)
    else:
        found = problems(args.folder)
        for problem in found:
            print("FAIL  " + problem)
        if found:
            return 1
        print(f"PASS  {args.folder} holds exactly the locked worker wheels")
    return 0


if __name__ == "__main__":
    sys.exit(main())
